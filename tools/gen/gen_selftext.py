"""Generate src/game/self_text.gen.cpp/.h: the string table of BiosGame.dll (LoadStringA(DAT_100c0de0, id)) as
`const char* dllString(int id)` (NULL for an unknown id).
Input: analysis/out/dll_stringtable.txt, lines `id<TAB>0xhex<TAB>text`; the text has a literal backslash-n for a newline
and keeps its trailing blanks (the original pads words with blanks to overwrite the previous word).
usage: python3 -I tools/gen/gen_selftext.py [stringtable.txt] [outdir]"""
import os
import sys

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, '..', 'analysis', 'out', 'dll_stringtable.txt')
outdir = sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, 'src', 'game')

entries = []
with open(src, 'rb') as f:
    for line in f.read().split(b'\n'):
        if not line or line.startswith(b'#'):
            continue
        parts = line.split(b'\t', 2)
        if len(parts) != 3:
            raise SystemExit('bad line: %r' % line)
        entries.append((int(parts[0]), parts[2].replace(b'\\n', b'\n')))
entries.sort()
ids = [e[0] for e in entries]
if len(set(ids)) != len(ids):
    raise SystemExit('duplicate string id')


def c_string(b):
    out = []
    for ch in b:
        if ch == 0x22: out.append('\\"')
        elif ch == 0x5c: out.append('\\\\')
        elif ch == 0x0a: out.append('\\n')
        elif ch == 0x3f: out.append('\\?')
        elif 0x20 <= ch < 0x7f: out.append(chr(ch))
        else: out.append('\\%03o' % ch)
    return '"' + ''.join(out) + '"'


with open(os.path.join(outdir, 'self_text.gen.h'), 'w') as f:
    f.write('// GENERATED by tools/gen/gen_selftext.py from analysis/out/dll_stringtable.txt; do not edit.\n'
            '#pragma once\n\nnamespace biosys::game {\n\n'
            '// LoadStringA(DAT_100c0de0, id, ...) of BiosGame.dll; NULL for an id the table does not hold.\n'
            'const char* dllString(int id);\n\n} // namespace biosys::game\n')
with open(os.path.join(outdir, 'self_text.gen.cpp'), 'w') as f:
    f.write('// GENERATED by tools/gen/gen_selftext.py from analysis/out/dll_stringtable.txt; do not edit.\n'
            '#include "game/self_text.gen.h"\n#include <algorithm>\n#include <iterator>\n\n'
            'namespace biosys::game {\n\nnamespace {\nstruct Entry { int id; const char* text; };\n'
            'const Entry kTable[] = {\n')
    for i, t in entries:
        f.write('    {%d, %s},\n' % (i, c_string(t)))
    f.write('};\n}\n\nconst char* dllString(int id) {\n'
            '    const Entry* e = std::lower_bound(std::begin(kTable), std::end(kTable), id,\n'
            '                                      [](const Entry& a, int v) { return a.id < v; });\n'
            '    return e != std::end(kTable) && e->id == id ? e->text : nullptr;\n}\n\n} // namespace biosys::game\n')
print('%d strings' % len(entries))
