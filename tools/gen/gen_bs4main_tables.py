#!/usr/bin/env python3
"""Generate src/engine/bs4main_tables.cpp: the data tables of the BS4 main-page dynamics (packet P3), read as data from
analysis/bin/BioSys.exe (never executed). usage: python3 -I tools/gen/gen_bs4main_tables.py > src/engine/bs4main_tables.cpp

Tables (spec analysis/notes/bs4.md section 3; every row layout checked against the readers in the decompile):
  exe:00488630 health table, stride 0x36, count dword at exe:00488c18: feature[0x15] dead[0xb] unhealthy[0xb] healthy[0xb]
  exe:00487290 device-highlight table, stride 0x1c, count dword at exe:0048777c: page[0xc] first last bit paramId
  exe:00486410 overlay list, stride 0x24: feature[0x15] ornament[0xb] state(+0x20, runtime; not emitted)
  exe:00488048 probe-page table, stride 0x48: page[0xb] bar[0xb] (+0x18) barHeight (+0x1c) rect l t r b (+0x2c) paramId
               (+0x30) min double (+0x38) max double (+0x40) defaultSensor; ends with an empty page name
  exe:00487c40 sensor list, stride 0x2b: feature[0x15] hotspot[0xb] ornament[0xb]; the last entry is the "null" sensor (world ids)
  exe:00487a98 alarm-probe table, stride 0x1c: mask1 mask2 page[0xc] (+0x14) first (+0x18) last; ends with an empty page name
  exe:00487780 alarm ornament list, stride 0x24: ornament[0xb] feature[0x15] state(+0x20)
"""
import os as _os
# the developer's folder above the repository (original discs, analysis notes); see WORKERS.md
_DEV = _os.environ.get('BIOSYS_DEV_ROOT') or _os.path.abspath(_os.path.join(_os.path.dirname(_os.path.abspath(__file__)), '..', '..', '..'))
import struct
import sys

EXE = (_DEV + '/analysis/bin/BioSys.exe')
d = open(EXE, 'rb').read()
pe = struct.unpack_from('<I', d, 0x3c)[0]
nsec = struct.unpack_from('<H', d, pe + 6)[0]
opt = struct.unpack_from('<H', d, pe + 20)[0]
base = struct.unpack_from('<I', d, pe + 24 + 28)[0]
secs = []
for i in range(nsec):
    _, vs, va, rs, ro = struct.unpack_from('<8sIIII', d, pe + 24 + opt + i * 40)
    secs.append((va, vs, ro, rs))


def off(va):
    r = va - base
    for a, vs, ro, rs in secs:
        if a <= r < a + max(vs, rs):
            return ro + r - a
    raise ValueError(hex(va))


def rd(va, n):
    o = off(va)
    return d[o:o + n]


def u32(va):
    return struct.unpack('<I', rd(va, 4))[0]


def i32(va):
    return struct.unpack('<i', rd(va, 4))[0]


def cs(va, n):
    b = rd(va, n)
    z = b.index(0) if 0 in b else n
    assert z < n, hex(va)
    return b[:z].decode('latin1')


def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


out = []
w = out.append
w('// GENERATED by tools/gen/gen_bs4main_tables.py from the data of analysis/bin/BioSys.exe; do not edit.')
w('// The tables the main-page dynamics of the BS4 terminal read (spec analysis/notes/bs4.md section 3); the exe address of each is in its comment.')
w('#include "engine/bs4main_priv.h"')
w('')
w('namespace biosys {')
w('namespace bs4main {')
w('')

n = u32(0x488c18)
assert n == 28
w('// exe:00488630 (count at exe:00488c18)')
w('const HealthRow kHealth[] = {')
for i in range(n):
    a = 0x488630 + i * 0x36
    w('    {%s, %s, %s, %s},' % (q(cs(a, 0x15)), q(cs(a + 0x15, 0xb)), q(cs(a + 0x20, 0xb)), q(cs(a + 0x2b, 0xb))))
w('};')
w('const size_t kHealthCount = %d;' % n)
w('')

n = u32(0x48777c)
assert n == 45
w('// exe:00487290 (count at exe:0048777c)')
w('const DeviceRow kDevices[] = {')
maxlast = 0
for i in range(n):
    a = 0x487290 + i * 0x1c
    first, last, bit, pid = struct.unpack('<IIII', rd(a + 0xc, 16))
    maxlast = max(maxlast, last)
    w('    {%s, %d, %d, %d, 0x%x},' % (q(cs(a, 0xc)), first, last, bit, pid))
w('};')
w('const size_t kDeviceCount = %d;' % n)
w('')

no = maxlast + 1
w('// exe:00486410 (%d overlays; the runtime state dword of the original is kept by the code)' % no)
w('const Overlay kOverlays[] = {')
for i in range(no):
    a = 0x486410 + i * 0x24
    w('    {%s, %s},' % (q(cs(a, 0x15)), q(cs(a + 0x15, 0xb))))
w('};')
w('const size_t kOverlayCount = %d;' % no)
w('')

w('// exe:00488048')
w('const ProbePage kProbePages[] = {')
n = 0
while cs(0x488048 + n * 0x48, 0xb) != '':
    a = 0x488048 + n * 0x48
    hgt, l, t, r, b, pid = struct.unpack('<6i', rd(a + 0x18, 24))
    mn, mx = struct.unpack('<dd', rd(a + 0x30, 16))
    ds = i32(a + 0x40)
    w('    {%s, %s, %d, {%d, %d, %d, %d}, 0x%x, %r, %r, %d},' % (q(cs(a, 0xb)), q(cs(a + 0xb, 0xb)), hgt, l, t, r, b, pid, mn, mx, ds))
    n += 1
w('};')
w('const size_t kProbePageCount = %d;' % n)
w('')

w('// exe:00487c40 (the last entry, feature "null", stands for the world parameters)')
w('const Sensor kSensors[] = {')
n = 0
while True:
    a = 0x487c40 + n * 0x2b
    w('    {%s, %s, %s},' % (q(cs(a, 0x15)), q(cs(a + 0x15, 0xb)), q(cs(a + 0x20, 0xb))))
    n += 1
    if cs(0x487c40 + n * 0x2b + 0x15, 0xb) == '':
        break
w('};')
w('const size_t kSensorCount = %d;' % n)
w('')

w('// exe:00487a98')
w('const AlarmPage kAlarmPages[] = {')
n = 0
maxlast = 0
while cs(0x487a98 + n * 0x1c + 8, 0xc) != '':
    a = 0x487a98 + n * 0x1c
    m1, m2 = struct.unpack('<II', rd(a, 8))
    first, last = struct.unpack('<II', rd(a + 0x14, 8))
    maxlast = max(maxlast, last)
    w('    {0x%x, 0x%x, %s, %d, %d},' % (m1, m2, q(cs(a + 8, 0xc)), first, last))
    n += 1
w('};')
w('const size_t kAlarmPageCount = %d;' % n)
w('')

na = maxlast + 1
assert 0x487780 + na * 0x24 == 0x487a98
w('// exe:00487780 (%d alarm ornaments; the state dword is kept by the code)' % na)
w('const AlarmOrnament kAlarmOrnaments[] = {')
for i in range(na):
    a = 0x487780 + i * 0x24
    w('    {%s, %s},' % (q(cs(a, 0xb)), q(cs(a + 0xb, 0x15))))
w('};')
w('const size_t kAlarmOrnamentCount = %d;' % na)
w('')
w('} // namespace bs4main')
w('} // namespace biosys')
sys.stdout.write('\n'.join(out) + '\n')
