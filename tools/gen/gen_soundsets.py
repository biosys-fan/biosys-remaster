#!/usr/bin/env python3
"""Generate src/game/soundsets.gen.cpp: the sound sets the CSite constructor arguments point to (DllPtr in
world_build.gen.cpp). A set is an array of 0x68-byte entries {char file[100]; int handle} in BiosGame.dll's .data;
entry 0 is {"count", n} and entries 1..n are the wav files (CSite::CloseSounds dll:1000e5d0 opens them, handles -1).
Static parsing of the PE image only. usage: gen_soundsets.py"""
import os as _os
# the developer's folder above the repository (original discs, analysis notes); see WORKERS.md
_DEV = _os.environ.get('BIOSYS_DEV_ROOT') or _os.path.abspath(_os.path.join(_os.path.dirname(_os.path.abspath(__file__)), '..', '..', '..'))
import os, re, struct

HERE = os.path.dirname(os.path.abspath(__file__))
PORT = os.path.normpath(os.path.join(HERE, '..', '..'))
DLL = (_DEV + '/analysis/bin/BiosGame.dll')
d = open(DLL, 'rb').read()
pe = struct.unpack_from('<I', d, 0x3c)[0]
nsec = struct.unpack_from('<H', d, pe + 6)[0]
opt = struct.unpack_from('<H', d, pe + 20)[0]
base = struct.unpack_from('<I', d, pe + 24 + 28)[0]
secs = []
for i in range(nsec):
    so = pe + 24 + opt + 40 * i
    vsz, va, rsz, ro = struct.unpack_from('<IIII', d, so + 8)
    secs.append((base + va, rsz, ro))

def off(v):
    for a, rs, ro in secs:
        if a <= v < a + rs:
            return v - a + ro
    raise SystemExit('address %x not in the image' % v)

src = open(os.path.join(PORT, 'src/game/world_build.gen.cpp')).read()
addrs = sorted(set(int(x, 16) for x in re.findall(r'DllPtr\{0x([0-9a-f]+)\}', src)))
out = ['// GENERATED by tools/gen/gen_soundsets.py from BiosGame.dll -- do not edit.',
       '#include "game/soundsets.h"', '', 'namespace biosys::game {', '',
       'const std::vector<SoundSetDef>& soundSetDefs() {',
       '    static const std::vector<SoundSetDef> defs = {']
for a in addrs:
    o = off(a)
    name = d[o:o + 100].split(b'\0')[0].decode('latin-1')
    count = struct.unpack_from('<I', d, o + 100)[0]
    if name != 'count' or count > 40:
        raise SystemExit('%x: not a sound set (%r, %d)' % (a, name, count))
    files = []
    for i in range(1, count + 1):
        b = o + 0x68 * i
        f = d[b:b + 100].split(b'\0')[0].decode('latin-1')
        h = struct.unpack_from('<i', d, b + 100)[0]
        if h != -1:
            raise SystemExit('%x entry %d: initial handle %d' % (a, i, h))
        files.append(f)
    out.append('        {0x%x, {%s}},' % (a, ', '.join('"%s"' % f.replace('\\', '\\\\') for f in files)))
out += ['    };', '    return defs;', '}', '', '} // namespace biosys::game', '']
open(os.path.join(PORT, 'src/game/soundsets.gen.cpp'), 'w').write('\n'.join(out))
print(len(addrs), 'sets')
