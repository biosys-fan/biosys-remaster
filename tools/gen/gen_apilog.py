#!/usr/bin/env python3
"""Generate src/game/apilog.gen.h/.cpp: LoggingApi, an EngineApi decorator that prints every call the game makes
(`--log-api`). Parsed from src/engine/engineapi.h, so it follows the interface automatically.
Line format: `api <Method> name=value ... -> <rc> [out name=value ...]`.
usage: gen_apilog.py   (run from anywhere; paths are derived from this file)"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PORT = os.path.normpath(os.path.join(HERE, '..', '..'))
hdr = open(os.path.join(PORT, 'src/engine/engineapi.h')).read()

def split_params(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch in '<(': depth += 1
        if ch in '>)': depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip()); cur = ''
        else:
            cur += ch
    if cur.strip(): out.append(cur.strip())
    return out

methods = []
for m in re.finditer(r'^\s*virtual int (\w+)\((.*)\) = 0;', hdr, re.M):
    name, plist = m.group(1), m.group(2)
    params = []
    for p in split_params(plist):
        mm = re.match(r'(.*?)(\w+)$', p)
        ty, nm = mm.group(1).strip(), mm.group(2)
        params.append((ty, nm))
    methods.append((name, params))

def fmt_in(ty, nm):
    """expression appended to the line before the call (inputs)"""
    t = ty.replace(' ', '')
    if t in ('conststd::string&',):
        return 'q(%s)' % nm
    if t == 'conststd::string*':
        return '(%s ? q(*%s) : std::string("null"))' % (nm, nm)
    if t in ('int', 'bool', 'u8', 'u32', 'int32_t'):
        return 'std::to_string(static_cast<long long>(%s))' % nm
    if t == 'constu8*':
        return 'ptr(%s, %d)' % (nm, 4 if nm == 'colourKey' else 1024)
    if t in ('constvoid*', 'void*'):
        return 'ptr(static_cast<const void*>(%s))' % nm
    return None

def is_out(ty):
    t = ty.replace(' ', '')
    return t in ('int&', 'std::string&', 'std::array<int,12>&', 'int*', 'u8*')

def fmt_out(ty, nm):
    t = ty.replace(' ', '')
    if t == 'int&': return 'std::to_string(%s)' % nm
    if t == 'std::string&': return 'q(%s)' % nm
    if t == 'std::array<int,12>&':
        return 'arr(%s)' % nm
    if t == 'int*': return '(%s ? std::to_string(*%s) : std::string("null"))' % (nm, nm)
    if t == 'u8*': return 'ptr(static_cast<const u8*>(%s))' % nm
    raise SystemExit('out ' + ty)

h = ['// GENERATED by tools/gen/gen_apilog.py from src/engine/engineapi.h -- do not edit.',
     '// LoggingApi: forwards every EngineApi call and reports it (`--log-api`).',
     '#pragma once', '#include "engine/engineapi.h"', '#include <functional>', '', 'namespace biosys::game {', '',
     'class LoggingApi final : public EngineApi {', 'public:',
     '    using Sink = std::function<void(const std::string&)>;',
     '    LoggingApi(EngineApi& inner, Sink sink) : inner_(inner), sink_(std::move(sink)) {}']
c = ['// GENERATED by tools/gen/gen_apilog.py from src/engine/engineapi.h -- do not edit.',
     '#include "game/apilog.gen.h"', '#include <cstdio>', '', 'namespace biosys::game {', '', 'namespace {',
     'std::string q(const std::string& s) {',
     '    std::string r = "\\"";',
     '    for (char ch : s) { if (ch == \'"\' || ch == \'\\\\\') r += \'\\\\\'; r += ch; }',
     '    return r + "\\"";', '}',
     'std::string ptr(const void* p) {',
     '    if (!p) return "null";',
     '    char b[32]; std::snprintf(b, sizeof b, "ptr#%08x", 0u);',
     '    return b;', '}',
     'std::string ptr(const u8* p, int n = 1024) {',
     '    if (!p) return "null";',
     '    // palettes (256 x 4 bytes) are identified by an FNV-1a hash of their bytes',
     '    uint32_t hsh = 2166136261u;',
     '    for (int i = 0; i < n; i++) hsh = (hsh ^ p[i]) * 16777619u;',
     '    char b[32]; std::snprintf(b, sizeof b, "pal#%08x", hsh);',
     '    return b;', '}',
     'std::string arr(const std::array<int, 12>& a) {',
     '    std::string r = "[";',
     '    for (size_t i = 0; i < a.size(); i++) r += (i ? "," : "") + std::to_string(a[i]);',
     '    return r + "]";', '}',
     '} // namespace', '']
for name, params in methods:
    sig = ', '.join('%s %s' % (t, n) for t, n in params)
    h.append('    int %s(%s) override;' % (name, sig))
    c.append('int LoggingApi::%s(%s) {' % (name, sig))
    ins = []
    for t, n in params:
        e = fmt_in(t, n)
        if e: ins.append((n, e))
    outs = [(t, n) for t, n in params if is_out(t)]
    # inputs are formatted before the call (the callee may change a buffer)
    c.append('    std::string line = "api %s";' % name)
    for n, e in ins:
        c.append('    line += " %s=" + %s;' % (n, e))
    # a `u8*` that is an out pointer (GetPalette) is not an input
    call = ', '.join(n for t, n in params)
    c.append('    int rc = inner_.%s(%s);' % (name, call))
    c.append('    line += " -> " + std::to_string(rc);')
    if outs:
        c.append('    if (rc == 0) {')
        c.append('        line += " out";')
        for t, n in outs:
            c.append('        line += " %s=" + %s;' % (n, fmt_out(t, n)))
        c.append('    }')
    c.append('    if (sink_) sink_(line);')
    c.append('    return rc;')
    c.append('}')
    c.append('')
h += ['', 'private:', '    EngineApi& inner_;', '    Sink sink_;', '};', '', '} // namespace biosys::game', '']
c += ['} // namespace biosys::game', '']
open(os.path.join(PORT, 'src/game/apilog.gen.h'), 'w').write('\n'.join(h))
open(os.path.join(PORT, 'src/game/apilog.gen.cpp'), 'w').write('\n'.join(c))
print('wrote %d methods' % len(methods))
