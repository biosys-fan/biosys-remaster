#!/usr/bin/env python3
"""Generates src/game/sim_tables.gen.cpp: the five step tables of CPlant::Update (photosynthesis lookups), read from the
DLL image. Each table is (x, y) double pairs; LookUpVal (dll:10007a60) is called with the index of the last entry
(0x13 / 0x17 in CPlant::Update dll:100733c0): light tables 20 entries, CO2 tables 24, temperature table 20.
Standard library only.  usage: python3 -I tools/gen/gen_simtables.py"""
import os as _os
# the developer's folder above the repository (original discs, analysis notes); see WORKERS.md
_DEV = _os.environ.get('BIOSYS_DEV_ROOT') or _os.path.abspath(_os.path.join(_os.path.dirname(_os.path.abspath(__file__)), '..', '..', '..'))
import os, struct, sys

DLL = (_DEV + '/analysis/bin/BiosGame.dll')
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'src', 'game', 'sim_tables.gen.cpp')
# (address, last index passed to LookUpVal, role)
TABLES = [
    (0x100bdad8, 0x13, 'light, C3 / CAM plants'),
    (0x100bdc18, 0x13, 'light, C4 plants'),
    (0x100bdd58, 0x17, 'CO2 percent, C3 / CAM plants'),
    (0x100bded8, 0x17, 'CO2 percent, C4 plants'),
    (0x100be058, 0x13, 'abs(leaf temperature - optimum), all plants'),
]

data = open(DLL, 'rb').read()
pe = struct.unpack_from('<I', data, 0x3c)[0]
nsec = struct.unpack_from('<H', data, pe + 6)[0]
optsz = struct.unpack_from('<H', data, pe + 20)[0]
base = struct.unpack_from('<I', data, pe + 24 + 28)[0]
secs = []
for i in range(nsec):
    so = pe + 24 + optsz + 40 * i
    vsz, va, rsz, ro = struct.unpack_from('<IIII', data, so + 8)
    secs.append((va, vsz, ro, rsz))

def off(vma):
    rva = vma - base
    for va, vsz, ro, rsz in secs:
        if va <= rva < va + rsz:
            return rva - va + ro
    raise SystemExit('address not in the image: %x' % vma)

lines = ['// GENERATED by tools/gen/gen_simtables.py from the DLL image; do not edit.',
         '#include "game/sim_tables.h"', '', 'namespace biosys::game {', '', 'namespace {']
for addr, last, role in TABLES:
    lines.append('// dll:%08x  %s: %d entries' % (addr, role, last + 1))
    lines.append('const double kTable_%08x[] = {' % addr)
    for k in range(last + 1):
        x, y = struct.unpack_from('<dd', data, off(addr + 16 * k))
        lines.append('    %r, %r,' % (x, y))
    lines.append('};')
lines += ['} // namespace', '', 'const StepTable* stepTable(uint32_t addr) {',
          '    static const StepTable kTables[] = {']
for addr, last, role in TABLES:
    lines.append('        {0x%08xu, %d, kTable_%08x},' % (addr, last, addr))
lines += ['    };', '    for (const StepTable& t : kTables)', '        if (t.addr == addr) return &t;', '    return nullptr;',
          '}', '', '} // namespace biosys::game', '']
open(OUT, 'w').write('\n'.join(lines))
print('wrote', os.path.normpath(OUT))
